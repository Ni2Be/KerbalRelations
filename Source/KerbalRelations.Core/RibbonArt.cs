        /// <summary>Names of the pictures a ribbon can use.</summary>
        public static IEnumerable<string> GlyphNames
        {
            get { return Glyphs.Keys; }
        }

        /// <summary>The rows of a picture from top to bottom; null if there is none with this name.</summary>
        public static string[] Glyph(string name)
        {
            string[] rows;
            return name != null && Glyphs.TryGetValue(name, out rows) ? rows : null;
        }

        /// <summary>
        /// The medal as RGBA bytes, top row first, <see cref="Width"/> x <see cref="Height"/> pixels
        /// times the scale. A ribbon without a known picture gets an empty badge.
        /// </summary>
        public static byte[] Render(RibbonDef def, int scale)
        {
            var stripes = Ribbons.ParseStripes(def.Stripes) ?? Ribbons.ParseStripes("777777");
            var total = 0d;
            for (int i = 0; i < stripes.Count; ++i)
                total += stripes[i].Width;
            var glyph = Glyph(def.Icon);

            // The badge takes the colour of the outer stripe; the picture is light on dark, dark on light.
            var face = stripes[0];
            var lightFace = (0.299d * face.R + 0.587d * face.G + 0.114d * face.B) / 255d > 0.62d;
            double inkR = lightFace ? 38d : 255d, inkG = lightFace ? 40d : 250d, inkB = lightFace ? 52d : 232d;

            var width = Width * scale;
            var height = Height * scale;
            var pixels = new byte[width * height * 4];
            for (int py = 0; py < height; ++py)
            {
                var y = (py + 0.5d) / scale;
                for (int px = 0; px < width; ++px)
                {
                    var x = (px + 0.5d) / scale;
                    double r = 0d, g = 0d, b = 0d, a = 0d;

                    if (x >= ClothLeft && x < ClothRight && y < ClothBottom)
                    {
                        var stripe = StripeAt(stripes, total, (x - ClothLeft) / (ClothRight - ClothLeft));
                        var edge = x < ClothLeft + 1d || x >= ClothRight - 1d || y < 1d;
                        var shade = edge ? 0.5d : 1.08d - 0.2d * y / ClothBottom;
                        r = stripe.R * shade;
                        g = stripe.G * shade;
                        b = stripe.B * shade;
                        a = 1d;
                    }

                    double dx = x - CentreX, dy = y - CentreY;
                    var distance = Math.Sqrt(dx * dx + dy * dy);
                    var cover = Clamp01((Radius - distance) * scale + 0.5d);
                    if (cover > 0d)
                    {
                        var shade = 1.1d - 0.24d * (dy + Radius) / (2d * Radius);
                        double br = face.R * shade, bg = face.G * shade, bb = face.B * shade;

                        var gx = (int)Math.Floor(x - GlyphX);
                        var gy = (int)Math.Floor(y - GlyphY);
                        if (glyph != null && gx >= 0 && gy >= 0 && gx < GlyphSize && gy < GlyphSize)
                        {
                            var mark = glyph[gy][gx];
                            var ink = mark == '#' ? 1d : mark == '+' ? 0.5d : 0d;
                            br += (inkR - br) * ink;
                            bg += (inkG - bg) * ink;
                            bb += (inkB - bb) * ink;
                        }

                        // A golden rim, lit from the top left, with a dark line around it.
                        var rim = Clamp01((distance - RimInner) * scale + 0.5d);
                        var glow = 1d - 0.3d * (dx + dy) / (2d * Radius);
                        br += (236d * glow - br) * rim;
                        bg += (192d * glow - bg) * rim;
                        bb += (74d * glow - bb) * rim;
                        var line = Clamp01((distance - (Radius - 0.7d)) * scale + 0.5d);
                        br += (96d - br) * line;
                        bg += (68d - bg) * line;
                        bb += (20d - bb) * line;

                        var alpha = cover + a * (1d - cover);
                        r = (br * cover + r * a * (1d - cover)) / alpha;
                        g = (bg * cover + g * a * (1d - cover)) / alpha;
                        b = (bb * cover + b * a * (1d - cover)) / alpha;
                        a = alpha;
                    }

                    var at = (py * width + px) * 4;
                    pixels[at] = ToByte(r);
                    pixels[at + 1] = ToByte(g);
                    pixels[at + 2] = ToByte(b);
                    pixels[at + 3] = ToByte(a * 255d);
                }
            }
            return pixels;
        }

        private static RibbonStripe StripeAt(List<RibbonStripe> stripes, double total, double fraction)
        {
            var at = fraction * total;
            for (int i = 0; i < stripes.Count; ++i)
            {
                at -= stripes[i].Width;
                if (at < 0d)
                    return stripes[i];
            }
            return stripes[stripes.Count - 1];
        }

        private static double Clamp01(double value)
        {
            return value < 0d ? 0d : value > 1d ? 1d : value;
        }

        private static byte ToByte(double value)
        {
            return (byte)Math.Max(0d, Math.Min(255d, Math.Round(value)));
        }
